def ask(payload):
    question = payload.get("question")
    if not isinstance(question, str) or not question.strip():
        raise ValueError("Введите вопрос")
    if len(question) > MAX_QUESTION_LENGTH:
        raise ValueError(f"Вопрос длиннее {MAX_QUESTION_LENGTH} символов")

    text = question.lower()
    for demo in DEMO_ANSWERS:
        if any(keyword in text for keyword in demo["keywords"]):
            return {"mode": MODE, "found": True, "answer": demo["answer"], "sources": demo["sources"]}
    return {"mode": MODE, "found": False, "answer": NOT_FOUND_ANSWER, "sources": []}


def program(payload):
    goal = payload.get("goal")
    level = payload.get("level")
    days = payload.get("days")
    equipment = payload.get("equipment")
    if goal not in GOALS:
        raise ValueError("Неизвестная цель")
    if level not in LEVELS:
        raise ValueError("Неизвестный уровень")
    if isinstance(days, bool) or not isinstance(days, int) or not 2 <= days <= 5:
        raise ValueError("Число дней должно быть от 2 до 5")
    if equipment not in DAY_TEMPLATES:
        raise ValueError("Неизвестное оборудование")

    templates = DAY_TEMPLATES[equipment]
    return {
        "mode": MODE,
        "title": f"Программа на {days} {_days_word(days)} в неделю, цель — {GOALS[goal]['label']}",
        "days": [
            {
                "name": f"День {number + 1}",
                "exercises": [
                    {"name": name, "sets": LEVELS[level], "reps": GOALS[goal]["reps"]}
                    for name in templates[number % len(templates)]
                ],
            }
            for number in range(days)
        ],
        "note": (
            "Тренировки на всё тело чередуются с днями отдыха [1]. "
            "Диапазон повторений выбран под цель [2]."
        ),
        "sources": PROGRAM_SOURCES,
    }


def _days_word(days):
    return "дней" if days == 5 else "дня"
