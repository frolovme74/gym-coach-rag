"""Промпты с недоверенными данными в отдельном JSON-сообщении."""

import json
import re


def passages(text):
    """Непересекающиеся дословные предложения с локальными номерами."""
    result = []
    for part in re.split(r"(?<=[.!?])\s+(?=[А-ЯA-Z«])|\n\s*\n", text):
        part = part.strip()
        while len(part) > 1500:
            end = part.rfind(" ", 0, 1500)
            end = end if end > 0 else 1500
            result.append(part[:end])
            part = part[end:].lstrip()
        if part:
            result.append(part)
    return result


