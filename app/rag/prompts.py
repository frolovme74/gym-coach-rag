def messages(kind, request, sources):
    return [
        {"role": "system", "content": ASK if kind == "ask" else PROGRAM},
        {
            "role": "user",
            "content": json.dumps(
                {
                    "question" if kind == "ask" else "parameters": request,
                    "sources": [
                        {
                            "source": n,
                            "title": s["title"],
                            "section": s["section"],
                            "passages": [
                                {"id": j, "text": part}
                                for j, part in enumerate(passages(s["fragment"]), 1)
                            ],
                        }
                        for n, s in enumerate(sources, 1)
                    ],
                },
                ensure_ascii=False,
            ),
        },
    ]
